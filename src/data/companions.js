/** 按 id 取道侣定义；不存在返回 null */
export function companionById(id) {
  return COMPANIONS.find((c) => c.id === id) || null;
}

/** 该境界下「已可结识」的道侣（metAt.realm <= realmIndex） */
export function companionsByRealm(ri) {
  const idx = Number.isFinite(ri) ? ri : 0;
  return COMPANIONS.filter((c) => (c.metAt?.realm ?? 0) <= idx);
}
