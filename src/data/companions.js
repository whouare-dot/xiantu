// src/data/companions.js
// 《仙途》道侣表（纯数据，无逻辑）。
//
// 设计基调：**同行，不是攻略**。
//   不做多角恋冲突、不做道德审判、不做后宫争宠。
//   每位道侣是"与你同走一段路的人"，有各自的来处与去处。
//
// 羁绊跨轮回保留 —— 这是这个系统存在的理由，也是最动人的地方。
//   转世后道侣不记得你，但你记得她。echo 段落写的就是这一刻。
//
// ────────────────────────── 字段说明 ──────────────────────────
//   metAt.realm   多少境界之后可以结识（realmIndex）
//   metAt.via     'encounter' 奇遇结识 | 'event' 事件结识（仅作展示与排期用）
//   bondBonus     羁绊分档加成；kind 必须落在已有系统的加成通道上：
//                 cultPct / atkPct / defPct / hpPct / comprehensionAdd / luckAdd / daoHeartAdd
//   story         专属剧情线；bond 是**解锁门槛**，gain 是读完后获得的羁绊
//   story[].effects 可选；走 systems/encounter.js 已有的效果 DSL，不另写解释器
//   echo          跨世重逢；条件为 state.reincarnation.count >= echo.minGen（只读不写）
//   encounter     专属奇遇；与 data/encounters.js 同构，效果用 DSL 的 flag 标记结识。
//                 接入 ENCOUNTERS 轮换由奇遇表维护者完成（本任务不改该文件）。

/** 专属奇遇结识后写入的剧情标记。isMet 同时认这个标记。 */
export function companionMeetFlag(id) {
  return 'cmp_met_' + id;
}

